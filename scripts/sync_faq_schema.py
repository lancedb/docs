"""Generate FAQPage JSON-LD from the visible questions and answers in docs/faq.

Run with --check in CI to detect stale markup. This intentionally handles the
prose, links, lists, inline code, and Tip/Warning callouts used by these FAQs,
and fails on anything else (fenced code, tables, blockquotes, reference links,
other MDX) rather than emitting text that differs from the rendered page.
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

from structured_data import CODE, render_jsonld, strip_markdown


FAQ_DIR = Path(__file__).resolve().parent.parent / "docs" / "faq"
FAQ_PAGES = ("index.mdx", "faq-oss.mdx", "faq-enterprise.mdx")
START = "{/* FAQ_SCHEMA:START — generated by python3 scripts/sync_faq_schema.py */}"
END = "{/* FAQ_SCHEMA:END */}"
HEADING = re.compile(r"^(#{2,6}) (.+)$", re.MULTILINE)
CALLOUT = re.compile(r"</?(?:Tip|Warning)>\s*")
FENCE = re.compile(r"^\s*(```|~~~)", re.MULTILINE)
UNSUPPORTED = re.compile(
    r"^\s*(?:\||>|\[[^\]]+\]:)"  # tables, blockquotes, link definitions
    r"|</?[A-Za-z][^>]*>|\{|\]\[",  # MDX components, expressions, reference links
    re.MULTILINE,
)


def plain_text(markdown: str) -> str:
    """Keep the full answer, including callout text and code identifiers."""
    if FENCE.search(markdown):
        raise ValueError("Fenced code needs explicit FAQ schema support")
    markdown = CALLOUT.sub("", markdown)
    if UNSUPPORTED.search(CODE.sub("", markdown)):
        raise ValueError("Unsupported Markdown or MDX")
    text = strip_markdown(re.sub(r"^\s*[-*] ", "", markdown, flags=re.MULTILINE))
    return " ".join(html.unescape(text).split())


def source_without_schema(source: str) -> str:
    if START not in source and END not in source:
        return source.rstrip()
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError("Expected one complete FAQ_SCHEMA block")
    start, end = source.index(START), source.index(END)
    if end < start or source[end + len(END):].strip():
        raise ValueError("FAQ_SCHEMA block must be at the end of the page")
    return source[:start].rstrip()


def faq_schema(source: str, slug: str) -> dict:
    headings = list(HEADING.finditer(source))
    questions = []
    for index, heading in enumerate(headings):
        title = heading.group(2).strip()
        end = headings[index + 1].start() if index + 1 < len(headings) else len(source)
        content = source[heading.end():end].strip()
        if not title.endswith("?"):
            # Category headings only group questions; any text under one
            # (or under a subheading inside an answer) would be left out.
            if content:
                raise ValueError(f"Text outside a question under heading: {title}")
            continue
        try:
            answer = plain_text(content)
            name = plain_text(title)
        except ValueError as error:
            raise ValueError(f"{error} in question: {title}") from error
        if not answer:
            raise ValueError(f"Missing answer: {title}")
        questions.append({
            "@type": "Question",
            "name": name,
            "acceptedAnswer": {"@type": "Answer", "text": answer},
        })
    if not questions:
        raise ValueError(f"No questions found in {slug}")
    url = f"https://docs.lancedb.com/{slug}"
    return {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "@id": f"{url}#faq",
        "url": url,
        "mainEntity": questions,
    }


def update_page(source: str, slug: str) -> str:
    body = source_without_schema(source)
    return f"{body}\n\n{START}\n{render_jsonld(faq_schema(body, slug))}{END}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if markup is stale")
    args = parser.parse_args()
    stale = []
    for name in FAQ_PAGES:
        path = FAQ_DIR / name
        source = path.read_text(encoding="utf-8")
        slug = "faq" if path.stem == "index" else f"faq/{path.stem}"
        try:
            updated = update_page(source, slug)
        except ValueError as error:
            print(f"{name}: {error}", file=sys.stderr)
            return 1
        if updated != source:
            if args.check:
                stale.append(name)
            else:
                path.write_text(updated, encoding="utf-8")
                print(f"Updated {name}")
    if stale:
        print(f"Stale FAQ schema: {', '.join(stale)}. Run python3 scripts/sync_faq_schema.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
