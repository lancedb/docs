"""Generate FAQPage JSON-LD from the visible questions and answers in docs/faq.

Run with --check in CI to detect stale markup. This intentionally handles the
prose, links, lists, inline code, and Tip/Warning callouts used by these FAQs;
extend it before introducing other MDX components or fenced examples.
"""

from __future__ import annotations

import argparse
import html
import re
from pathlib import Path

from structured_data import render_jsonld


FAQ_DIR = Path(__file__).resolve().parent.parent / "docs" / "faq"
START = "{/* FAQ_SCHEMA:START — generated by python3 scripts/sync_faq_schema.py */}"
END = "{/* FAQ_SCHEMA:END */}"
HEADING = re.compile(r"^#{2,6} (.+)$", re.MULTILINE)
LINK = re.compile(r"\[([^\]]+)\]\((?:[^()\n]|\([^()\n]*\))*\)")


def plain_text(markdown: str) -> str:
    """Keep the full answer, including callout text and code identifiers."""
    if re.search(r"^\s*(```|~~~)", markdown, re.MULTILINE):
        raise ValueError("Fenced code needs explicit FAQ schema support")
    code = []

    def protect_code(match: re.Match) -> str:
        code.append(match.group(1))
        return f"\x00{len(code) - 1}\x00"

    text = re.sub(r"`([^`]+)`", protect_code, markdown)
    text = re.sub(r"</?(?:Tip|Warning)>\s*", "", text)
    if re.search(r"</?[A-Za-z][^>]*>|\{", text):
        raise ValueError("Unsupported MDX in FAQ answer")
    text = re.sub(r"!\[[^\]]*\]\([^\n]*\)", "", text)
    text = LINK.sub(r"\1", text)
    text = re.sub(r"\*{1,2}([^*]+)\*{1,2}", r"\1", text)
    text = re.sub(r"^\s*[-*] ", "", text, flags=re.MULTILINE)
    text = re.sub(r"\x00(\d+)\x00", lambda match: code[int(match.group(1))], text)
    return " ".join(html.unescape(text).split())


def source_without_schema(source: str) -> str:
    if START not in source and END not in source:
        return source.rstrip()
    if source.count(START) != 1 or source.count(END) != 1:
        raise ValueError("Expected one complete FAQ_SCHEMA block")
    start, end = source.index(START), source.index(END)
    if end < start or source[end + len(END):].strip():
        raise ValueError("FAQ_SCHEMA block must be at the end of the page")
    return source[:start].rstrip()


def faq_schema(source: str, slug: str) -> dict:
    headings = list(HEADING.finditer(source))
    questions = []
    for index, heading in enumerate(headings):
        question = heading.group(1)
        if not question.endswith("?"):
            continue
        end = headings[index + 1].start() if index + 1 < len(headings) else len(source)
        answer = plain_text(source[heading.end():end])
        if not answer:
            raise ValueError(f"Missing answer: {question}")
        questions.append({
            "@type": "Question",
            "name": plain_text(question),
            "acceptedAnswer": {"@type": "Answer", "text": answer},
        })
    if not questions:
        raise ValueError(f"No questions found in {slug}")
    url = f"https://docs.lancedb.com/{slug}"
    return {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "@id": f"{url}#faq",
        "url": url,
        "mainEntity": questions,
    }


def update_page(source: str, slug: str) -> str:
    body = source_without_schema(source)
    return f"{body}\n\n{START}\n{render_jsonld(faq_schema(body, slug))}{END}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if markup is stale")
    args = parser.parse_args()
    stale = []
    for path in sorted(FAQ_DIR.glob("*.mdx")):
        source = path.read_text()
        slug = "faq" if path.stem == "index" else f"faq/{path.stem}"
        updated = update_page(source, slug)
        if updated != source:
            if args.check:
                stale.append(path.name)
            else:
                path.write_text(updated)
                print(f"Updated {path.name}")
    if stale:
        print(f"Stale FAQ schema: {', '.join(stale)}. Run python3 scripts/sync_faq_schema.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
